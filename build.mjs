import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
await build({entryPoints:['source-app.js'],bundle:true,format:'esm',target:['safari16','chrome110'],outfile:'app.js',minify:true});
const html=await readFile('source-index.html','utf8'),hash=createHash('sha256').update(html);
for(const f of ['app.js','styles.css','leaflet.css','source-sw.js'])hash.update(await readFile(f));
const version=hash.digest('hex').slice(0,12);
await writeFile('index.html',html.replace('./app.js','./app.js?v='+version).replace('./styles.css','./styles.css?v='+version).replace('./leaflet.css','./leaflet.css?v='+version));
await writeFile('sw.js',(await readFile('source-sw.js','utf8')).replaceAll('__VERSION__',version));
console.log('CampusPark ready for GitHub Pages. Version '+version);
